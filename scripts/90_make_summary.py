"""results/RESULTS_SUMMARY.md: every headline number with the file it came from (CLAUDE.md 7).
Limitations are copied from docs/DEVIATIONS.md. Sections for phases not yet run say so."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from p012.config import ROOT, path  # noqa: E402

R = path("results")


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def ms(df, method, col, digits=4):
    r = df.set_index("method").loc[method]
    return f"{r[f'{col}_mean']:.{digits}f} ± {r[f'{col}_std']:.{digits}f}"


def bc_section(lines):
    t2f, t3f, t4f, t5f = (R / "tables" / f"{s}.csv" for s in
                          ("T2_bc_holdoutA", "T3_bc_holdoutB", "T4_bc_cv5", "T5_bc_ablation"))
    runs_f = R / "runs" / "all_runs.csv"
    if not t2f.exists():
        lines.append("BreastCancer results not produced yet (Phase 3).\n")
        return
    t2, t3, t4, t5 = (pd.read_csv(f) for f in (t2f, t3f, t4f, t5f))
    runs = pd.read_csv(runs_f)
    a = runs[runs.protocol == "holdoutA"]
    val = a[a.method.isin(t2.method)].groupby("method").val_auc.mean()
    best = val.idxmax()
    lines += [
        "## BreastCancer, course protocol (Phase 3)", "",
        f"**Best method by mean validation AUC on hold-out A: {best}** (validation AUC {val[best]:.4f}; "
        f"source `{rel(runs_f)}`, column `val_auc`). Its test metrics, mean ± std over 5 seeds "
        f"(source `{rel(t2f)}`):", "",
        "| metric | value |", "|---|---|",
    ]
    lines += [f"| {m} | {ms(t2, best, m)} |" for m in ("accuracy", "precision", "recall", "f1", "auc")]
    lines += ["", f"Test AUC per method (hold-out A, `{rel(t2f)}`; hold-out B, `{rel(t3f)}`; "
                  f"5-fold CV, `{rel(t4f)}`):", "",
              "| method | hold-out A | hold-out B | 5-fold CV | fit time A (s) |", "|---|---|---|---|---|"]
    for m in t2.method:
        lines.append(f"| {m} | {ms(t2, m, 'auc')} | {ms(t3, m, 'auc')} | {ms(t4, m, 'auc')} | "
                     f"{ms(t2, m, 'seconds', 1)} |")
    lines += ["", f"5-fold CV accuracy, mean ± std (`{rel(t4f)}`): " +
              ", ".join(f"{m} {ms(t4, m, 'accuracy')}" for m in t4.method), ""]

    # s-MLE vs s-Optuna, paired per seed
    piv = a[a.method.isin(["PFNB-MLE", "PFNB-Optuna"])].pivot(index="seed", columns="method",
                                                               values=["auc", "seconds", "s"])
    d = piv["auc"]["PFNB-MLE"] - piv["auc"]["PFNB-Optuna"]
    lines += ["### s-MLE vs s-Optuna (hold-out A, 5 seeds, source `" + rel(runs_f) + "`)", "",
              f"- Test AUC difference (MLE − Optuna): mean {d.mean():+.4f}, std {d.std():.4f}, "
              f"MLE higher in {(d > 0).sum()} / ties {(d == 0).sum()} / lower in {(d < 0).sum()} of {len(d)} seeds.",
              f"- Fit time: PFNB-MLE {piv['seconds']['PFNB-MLE'].mean():.1f} s, "
              f"PFNB-Optuna {piv['seconds']['PFNB-Optuna'].mean():.1f} s per run (mean; both include TabPFN time; "
              "Optuna's includes its stage-1 tree trials).",
              "- Learned s per seed: MLE " + ", ".join(f"{v:.3g}" for v in piv["s"]["PFNB-MLE"]) +
              "; Optuna " + ", ".join(f"{v:.3g}" for v in piv["s"]["PFNB-Optuna"]) + ".", ""]
    lines += [f"### Ablations (hold-out A, `{rel(t5f)}`)", "", "| method | change | test AUC | test log-loss | ECE |",
              "|---|---|---|---|---|"]
    lines += [f"| {r.method} | {r.change} | {ms(t5, r.method, 'auc')} | {ms(t5, r.method, 'log_loss')} | "
              f"{ms(t5, r.method, 'ece')} |" for r in t5.itertuples()]
    lines.append("")


def main():
    lines = ["# RESULTS SUMMARY (generated by `scripts/90_make_summary.py`; do not edit by hand)", ""]
    bc_section(lines)
    lines += ["## Sweep, paper comparison, meta-study", "",
              "Not run yet (Phases 4-6): paper vs ours (RQ1), number of datasets where PFN-Boost helps, "
              "LODO regret per policy (RQ3).", ""]
    dev = (ROOT / "docs" / "DEVIATIONS.md").read_text().splitlines()
    lines += ["## Limitations and caveats (from `docs/DEVIATIONS.md`)", ""] + [l for l in dev if l.startswith("- ")]
    out = R / "RESULTS_SUMMARY.md"
    out.write_text("\n".join(lines) + "\n")
    print(out)


if __name__ == "__main__":
    main()
