"""Phase 4 check (CLAUDE.md 8): our sweep AUCs vs the paper's Table 3 for the piloted datasets, and an
estimate of the full-sweep wall-clock time from the measured unit times (CLAUDE.md 5.3).
Writes results/tables/P4_pilot_vs_paper.{csv,md,tex} and results/P4_time_estimate.md."""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from p012.config import ROOT, load_config, path  # noqa: E402
from p012.data import load_dataset, paper_full_counts, sweep_sizes  # noqa: E402
from p012.report import load_runs, write_table  # noqa: E402

# our method -> paper Table 3 column
PAPER_COL = {"XGB": "xgb_auc", "TabPFN": "tabpfn_auc", "Selection": "selection_auc", "Stacking": "stacking_auc",
             "PFNB-Optuna": "pfnboost_auc"}


def comparison(runs):
    sw = runs[runs.protocol == "sweep"]
    ours = sw.groupby(["dataset", "size", "method"]).auc.agg(["mean", "count"]).reset_index()
    ref = pd.read_csv(path("paper_reference"))
    rows = []
    for (d, size), g in ours.groupby(["dataset", "size"]):
        r = ref[(ref.dataset == d) & (ref.size_label == str(size))]
        for m, col in PAPER_COL.items():
            o = g[g.method == m]
            if o.empty:
                continue
            paper = float(r[col].iloc[0]) if not r.empty else np.nan
            rows.append({"dataset": d, "size": str(size), "method": m, "ours": float(o["mean"].iloc[0]),
                         "paper": paper, "diff": float(o["mean"].iloc[0]) - paper, "n_seeds": int(o["count"].iloc[0])})
    df = pd.DataFrame(rows)
    order = {s: i for i, s in enumerate(["10", "25", "50", "100", "250", "500", "full"])}
    return df.sort_values(["dataset", "size", "method"], key=lambda c: c.map(order) if c.name == "size" else c)


def time_estimate():
    """Per unit: the pilot fit log(wall time) = a + b log(n_train) for n_train inside the pilot's range.
    Above it, the larger of that and a cost model from the jungle-full probe (results/P4_probe_large.json):
    TabPFN seconds per scored row x rows scored, plus tree fits per unit x probe seconds per fit scaled
    linearly in n_train. 05_sweep.py scores TabPFN one unit at a time, so that part is not divided by n_jobs."""
    units = [json.loads(f.read_text()) for f in (path("results") / "runs" / "sweep").glob("*/*/*/unit_time.json")]
    t = pd.DataFrame(units)
    b, a = np.polyfit(np.log(t.n_train), np.log(t.wall_seconds), 1)
    probe = json.loads((path("results") / "P4_probe_large.json").read_text())
    cfg = load_config()
    h = cfg["hpo"]
    fits = 2 * h["trials_xgb"] + h["trials_pfnb"] + h["trials_s"] + cfg["s_joint"]["rounds"] + 1
    n_jobs = max(1, os.cpu_count() // cfg["xgb"]["nthread"])
    rows = []
    for name in cfg["datasets"]["sweep"]:
        ds = load_dataset(name)
        for size in sweep_sizes(ds):
            n_tr, n_va = paper_full_counts(name) if size == "full" else (int(size), int(size))
            pilot = float(np.exp(a + b * np.log(n_tr)))
            tab = probe["tabpfn_seconds"] / probe["tabpfn_rows_scored"] * (2 * n_tr + n_va + len(ds.y_test))
            trees = fits * probe["xgb_trial_seconds_mean"] * n_tr / probe["n_train"]
            big = n_tr > t.n_train.max() and tab + trees > pilot
            rows.append({"dataset": name, "size": size, "n_train": n_tr, "model": "probe" if big else "pilot",
                         "seq_seconds": tab * len(cfg["seeds"]) if big else 0.0,
                         "par_seconds": (trees if big else pilot) * len(cfg["seeds"])})
    est = pd.DataFrame(rows)
    est["hours"] = (est.seq_seconds + est.par_seconds / n_jobs) / 3600
    return t, est, a, b, n_jobs, probe, fits


def main():
    runs = load_runs()
    cmp = comparison(runs)
    write_table(cmp, "P4_pilot_vs_paper")
    full = cmp[cmp["size"] == "full"]
    print(cmp.to_string(index=False))

    t, est, a, b, n_jobs, probe, fits = time_estimate()
    total_h = est.hours.sum()
    per_ds = est.groupby("dataset").hours.sum().sort_values(ascending=False)
    big = est[est.model == "probe"]
    lines = [
        "# Phase 4: full-sweep time estimate (generated by `scripts/06_pilot_check.py`)", "",
        f"Pilot: {len(t)} sweep units (`results/runs/sweep/*/*/*/unit_time.json`), n_train {t.n_train.min()}-"
        f"{t.n_train.max()}, unit wall time {t.wall_seconds.min():.0f}-{t.wall_seconds.max():.0f} s.",
        f"Model: log(seconds) = {a:.2f} + {b:.2f} log(n_train), fitted on the pilot units; "
        f"{n_jobs} parallel workers; {len(load_config()['seeds'])} seeds.",
        f"Large units ({', '.join(f'{r.dataset} {r.size}' for r in big.itertuples())}) use the probe "
        f"`results/P4_probe_large.json` instead ({probe['dataset']} {probe['size']}, n_train {probe['n_train']}: "
        f"TabPFN {probe['tabpfn_seconds']:.0f} s for {probe['tabpfn_rows_scored']} scored rows, "
        f"{probe['xgb_trial_seconds_mean']:.1f} s per XGBoost fit, {fits} fits per unit).", "",
        f"**Estimated full sweep: {total_h:.1f} hours** (all {len(est)} dataset x size cells x seeds; "
        f"of which {est.seq_seconds.sum() / 3600:.1f} h sequential TabPFN scoring of the large units).", "",
        "| dataset | estimated hours |", "|---|---|"] + [f"| {d} | {h:.2f} |" for d, h in per_ds.items()]
    lines += ["", "Full-size AUC check vs the paper (|ours − paper| > 0.02 flagged), source "
              "`results/tables/P4_pilot_vs_paper.csv`:", "", "| dataset | method | ours | paper | diff | flag |",
              "|---|---|---|---|---|---|"]
    lines += [f"| {r.dataset} | {r.method} | {r.ours:.4f} | {r.paper:.4f} | {r.diff:+.4f} | "
              f"{'**> 0.02**' if abs(r.diff) > 0.02 else ''} |" for r in full.itertuples()]
    out = path("results") / "P4_time_estimate.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))
    print(out.relative_to(ROOT))


if __name__ == "__main__":
    main()
